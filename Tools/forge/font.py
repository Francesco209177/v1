def build(out_dir: str) -> str:
    sheet = Sheet("Font a pixel")
    pal = sheet.add_palette(Palette("font", {"w": "#ffffff"}))
    for ch, rows in sorted(GLYPHS.items(), key=lambda kv: ord(kv[0])):
        widths = {len(r) for r in rows}
        if len(rows) not in (7, 9) or len(widths) != 1:
            raise ValueError(f"glifo {ch!r} malformato")
        grid = Grid.from_rows([r.replace("#", "w") for r in rows])
        sheet.add(f"font_{ord(ch)}", grid, pal, ax=0, ay=7)
    path = f"{out_dir}/font.spr"
    sheet.write(path)
    return path
